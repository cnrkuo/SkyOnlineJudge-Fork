#!/bin/sh
# One-step production deployment with Docker Compose.
#
#   sh docker/prod.sh            build the images and start (or update) the stack
#   sh docker/prod.sh --no-build start without rebuilding
#
# On the first run it writes .env.production with freshly generated
# secrets. Keep that file: the database and queue volumes are initialised
# with its passwords. Extra arguments go to `docker compose up`.
set -eu
cd "$(dirname "$0")/.."
env_file="${ENV_FILE:-.env.production}"

if [ ! -f "$env_file" ]; then
  secret() { od -An -tx1 -N32 /dev/urandom | tr -d ' \n'; }
  umask 077
  cat > "$env_file" <<ENV
# Generated by docker/prod.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep it private and backed up.
POSTGRES_PASSWORD=$(secret)
RABBITMQ_PASSWORD=$(secret)
SESSION_SECRET=$(secret)
# Shared by the API and the bundled judge container.
JUDGE_TOKEN=skyoj_judge_$(secret)

# Where the web app is published. Serve it through a TLS reverse proxy;
# set COOKIE_SECURE=false only to try it out over plain HTTP.
WEB_BIND=0.0.0.0
WEB_PORT=3000
COOKIE_SECURE=true
# The API is published for judges on other machines; keep it private.
API_BIND=127.0.0.1
API_PORT=3001

SITE_NAME=Sky Online Judge
SITE_TIMEZONE=Asia/Taipei
# MAX_UPLOAD_MB=256
# JUDGE_TIMEOUT_SEC=600
# Image tag of skyoj/api, skyoj/web and skyoj/judge.
# SKYOJ_TAG=latest
# Builds behind a TLS-intercepting proxy: export BUILD_CA_CERT="$(cat proxy-ca.pem)"
# before running docker/prod.sh.
ENV
  echo "Created $env_file with new secrets."
fi

build=--build
for arg in "$@"; do [ "$arg" = --no-build ] && build=; done
docker compose -f compose.prod.yaml --env-file "$env_file" up -d $build --wait "$@"
port=$(sed -n 's/^WEB_PORT=//p' "$env_file")
echo "Sky Online Judge is up on port ${port:-3000}. The first account registered becomes the site owner."
